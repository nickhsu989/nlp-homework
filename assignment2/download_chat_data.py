def build_seed_convs() -> list:
    """作業範例與精選對話，原樣保留。"""
    return [list(conv) for conv in SEED_CONVS]


def build_generated_convs(rng: random.Random, count: int) -> list:
    """
    從主題模組產生 count 段多輪對話。

    做法：
    1. 隨機挑一個模組。
    2. 開場使用該模組的 open。
    3. 每一輪從該模組的 asks / answers 中各挑一種說法，
       組出「使用者追問 → 專家回應」。

    這樣可以保持每段對話的主題連貫，
    同時讓表面字詞有足夠的變化，
    避免模型只學會背誦少數幾句固定的話。

    同一段 conversation 只保留一次；若隨機抽到重複組合，
    會重新抽，直到達到 count 段不重複的對話。
    """
    convs = []
    seen = set()
    max_attempts = max(1000, count * 100)

    for _ in range(max_attempts):
        if len(convs) >= count:
            break

        module = rng.choice(TOPIC_MODULES)

        conversation = [("user", module["open"])]

        for index in range(len(module["rounds"])):
            _, default_answer = module["rounds"][index]

            ask_options = module["asks"][index]
            answer_options = module["answers"][index]

            ask = rng.choice(ask_options)
            answer = rng.choice(answer_options) if answer_options else default_answer

            conversation.append(("assistant", answer))
            conversation.append(("user", ask))

        signature = tuple(conversation)
        if signature in seen:
            continue

        seen.add(signature)
        convs.append(conversation)

    if len(convs) != count:
        raise RuntimeError(
            f"only generated {len(convs)} unique conversations; expected {count}"
        )

    return convs


def main():
    rng = random.Random(RNG_SEED)

    seed_convs = build_seed_convs()
    generated_convs = build_generated_convs(
        rng,
        count=TARGET_CONVERSATIONS - len(seed_convs),
    )

    all_convs = seed_convs + generated_convs
    rng.shuffle(all_convs)

    with OUTPUT.open("w", encoding="utf-8") as f:
        for c in all_convs:
            msgs = [{"role": "system", "content": SYSTEM}]
            for role, content in c:
                msgs.append({"role": role, "content": content})
            f.write(json.dumps({"messages": msgs}, ensure_ascii=False) + "\n")

    unique_openings = len({c[0][1] for c in all_convs})

    print(f"wrote {len(all_convs)} conversations to {OUTPUT}")
    print(f"  seed conversations     : {len(seed_convs)}")
    print(f"  generated conversations : {len(generated_convs)}")
    print(f"  unique topic modules   : {len(TOPIC_MODULES)}")
    print(f"  unique openings        : {unique_openings}")
    print(f"  turns per conversation : 4")


if __name__ == "__main__":
    main()
